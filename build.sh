#!/bin/bash
set -e

echo "=== makuharistudio portfolio build ==="

PROJECT_ROOT="$(cd "$(dirname "$0")" && pwd)"
SOURCE="$PROJECT_ROOT/source"
DIST="$PROJECT_ROOT/dist"

# ---------------------------------------------------------------------------
# Helper: copy only when the destination is missing or content differs.
# Order of checks (cheap → definitive):
#   1. destination missing
#   2. sizes differ
#   3. byte-for-byte content (cmp -s)
# Identical files are left untouched (no write, no mtime update).
# ---------------------------------------------------------------------------
copy_if_different() {
  local src="$1" dest="$2"

  if [[ ! -f "$src" ]]; then
    echo "WARNING: source missing: $src" >&2
    return 1
  fi

  if [[ ! -f "$dest" ]]; then
    mkdir -p "$(dirname "$dest")"
    cp -a "$src" "$dest"
    return 0
  fi

  local src_size dest_size
  src_size=$(stat -c%s "$src" 2>/dev/null || echo 0)
  dest_size=$(stat -c%s "$dest" 2>/dev/null || echo 0)

  if [[ "$src_size" != "$dest_size" ]]; then
    cp -a "$src" "$dest"
    return 0
  fi

  if ! cmp -s "$src" "$dest"; then
    cp -a "$src" "$dest"
    return 0
  fi

  # Identical — do nothing
  return 0
}

# ---------------------------------------------------------------------------
# Helper: sync a source directory tree into a destination.
# - Copies new/changed files via copy_if_different
# - Removes files in dest that no longer exist in source (keeps the tree clean)
# ---------------------------------------------------------------------------
sync_dir() {
  local src_dir="$1" dest_dir="$2"

  mkdir -p "$dest_dir"

  # Copy / update files
  while IFS= read -r -d '' srcfile; do
    local rel="${srcfile#"$src_dir"/}"
    copy_if_different "$srcfile" "$dest_dir/$rel"
  done < <(find "$src_dir" -type f -print0)

  # Remove stale files in dest that are no longer in source
  if [[ -d "$dest_dir" ]]; then
    while IFS= read -r -d '' destfile; do
      local rel="${destfile#"$dest_dir"/}"
      if [[ ! -f "$src_dir/$rel" ]]; then
        rm -f "$destfile"
      fi
    done < <(find "$dest_dir" -type f -print0)
  fi
}

echo "Preparing output directories..."
mkdir -p "$DIST" "$SOURCE/library"

# ---------------------------------------------------------------------------
# Generate catalog.ts only if content actually changed
# ---------------------------------------------------------------------------
echo "Generating catalog (build-time index)..."

CATALOG_TMP=$(mktemp)
cat > "$CATALOG_TMP" << EOF
// Auto-generated by build.sh — DO NOT EDIT
export const catalog = {
  posts: [
$(cd "$SOURCE/markdown/posts" 2>/dev/null && ls -1 *.md 2>/dev/null | sort -r | sed 's/^/    "/;s/$/",/' || true)
  ],
  projects: [
$(cd "$SOURCE/markdown/projects" 2>/dev/null && ls -1 *.md 2>/dev/null | sort -r | sed 's/^/    "/;s/$/",/' || true)
  ],
  readings: [
$(cd "$SOURCE/markdown/readings" 2>/dev/null && ls -1 *.md 2>/dev/null | sort -r | sed 's/^/    "/;s/$/",/' || true)
  ],
  games: [
$(cd "$SOURCE/games" 2>/dev/null && ls -1 *.ts *.tsx 2>/dev/null | sed 's/\.tsx\?$//' | grep -E '^(DualNBack|RocketLaunchSimulation|SatelliteCoverageOptimiser|VocabularyTrainer)$' | sed 's/^/    "/;s/$/",/' || true)
  ]
} as const;

export type ContentType = keyof typeof catalog;
EOF

copy_if_different "$CATALOG_TMP" "$SOURCE/library/catalog.ts"
rm -f "$CATALOG_TMP"
echo "Catalog ready."

# ---------------------------------------------------------------------------
# Generate markdown-raw.ts only if content actually changed
# ---------------------------------------------------------------------------
echo "Generating markdown raw loaders..."

RAW_TMP=$(mktemp)
python3 - "$RAW_TMP" << 'PY'
import sys
from pathlib import Path

out_path = Path(sys.argv[1])
root = Path("source/markdown")
lines = [
    "// Auto-generated by build.sh — DO NOT EDIT",
    "// esbuild --loader:.md=text turns each import into the file contents.",
    "// @ts-nocheck",
    "export const rawFiles: Record<string, string> = {",
]
for kind in ("posts", "projects", "readings"):
    folder = root / kind
    if not folder.exists():
        continue
    for path in sorted(folder.glob("*.md"), reverse=True):
        key = f"{kind}/{path.name}"
        ident = f"{kind}_{path.stem.replace('-', '_')}"
        lines.append(f"  '{key}': {ident},")
lines.append("};")
lines.append("")
for kind in ("posts", "projects", "readings"):
    folder = root / kind
    if not folder.exists():
        continue
    for path in sorted(folder.glob("*.md"), reverse=True):
        ident = f"{kind}_{path.stem.replace('-', '_')}"
        rel = f"../markdown/{kind}/{path.name}"
        lines.append(f"import {ident} from '{rel}';")

out_path.write_text("\n".join(lines) + "\n")
print(f"wrote {len(lines)} lines to temp")
PY

copy_if_different "$RAW_TMP" "$SOURCE/library/markdown-raw.ts"
rm -f "$RAW_TMP"

# ---------------------------------------------------------------------------
# Type check
# ---------------------------------------------------------------------------
if ! command -v tsc >/dev/null 2>&1; then
  echo "ERROR: tsc not found. Run: sudo dnf install -y typescript"
  exit 1
fi

if ! command -v esbuild >/dev/null 2>&1; then
  echo "ERROR: esbuild not found."
  exit 1
fi

echo "Type checking with tsc..."
tsc --noEmit --pretty false
echo "Type checking passed."

# ---------------------------------------------------------------------------
# Bundle with esbuild → temp file, then replace only if different
# ---------------------------------------------------------------------------
echo "Bundling with esbuild..."
mkdir -p "$DIST/js"

ESBUILD_TMP=$(mktemp)
esbuild source/main.ts \
  --bundle \
  --outfile="$ESBUILD_TMP" \
  --format=esm \
  --target=es2022 \
  --loader:.md=text \
  --log-level=warning

copy_if_different "$ESBUILD_TMP" "$DIST/js/main.js"
rm -f "$ESBUILD_TMP"

# ---------------------------------------------------------------------------
# Sync static assets (only write when content differs)
# ---------------------------------------------------------------------------
echo "Syncing static assets..."

sync_dir "$SOURCE/assets" "$DIST/assets"
sync_dir "$SOURCE/themes" "$DIST/themes"

# Game card images (only the image files that sit next to the modules)
mkdir -p "$DIST/assets/games"
while IFS= read -r -d '' img; do
  copy_if_different "$img" "$DIST/assets/games/$(basename "$img")"
done < <(find "$SOURCE/games" -maxdepth 1 -type f \
  \( -name '*.png' -o -name '*.jpg' -o -name '*.gif' -o -name '*.webp' \) -print0)

# robots.txt (optional)
if [[ -f "$SOURCE/assets/robots.txt" ]]; then
  copy_if_different "$SOURCE/assets/robots.txt" "$DIST/robots.txt"
fi

# index.html
echo "Syncing index.html..."
copy_if_different "$PROJECT_ROOT/index.html" "$DIST/index.html"

echo ""
echo "Build completed successfully!"
echo "Output: $DIST"
echo ""
echo "To test locally, run:"
echo "    python3 -m http.server 8000 --directory dist"
echo "Then open http://localhost:8000"
